-- Splitset maps: routes the user draws point by point (the course builder).
--
-- A drawn route is a list of waypoints the user placed on the map; the app routes between them
-- on foot (Valhalla over OpenStreetMap) and stores the result like any other route: polyline,
-- distance, climb and descent. The waypoints are kept too, so the course can be opened in the
-- builder again and changed. Generated routes (loop, point_to_point) leave them null.
--
-- Routes of every kind can be exported as GPX and imported into Garmin Connect as a Course.

alter table public.routes drop constraint routes_kind_check;
alter table public.routes add constraint routes_kind_check check (kind in ('loop', 'point_to_point', 'drawn'));

alter table public.routes
  add column waypoints jsonb;                                  -- [[lat, lng], ...] as placed; null for generated routes

comment on column public.routes.waypoints is
  'The points the user placed in the course builder, [[lat, lng], ...] in order, for editing the course again. Null for generated routes.';

comment on table public.routes is
  'Saved routes: generated by target distance and start/end point, or drawn point by point, over real roads and paths (pedestrian routing). Exported as GPX for Garmin Connect; not synced to the watch directly.';
