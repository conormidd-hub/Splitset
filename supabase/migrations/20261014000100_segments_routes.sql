-- Splitset maps: segments, segment efforts and saved routes.
--
-- segments         a stretch of trail the user picked from one of their runs (Strava-style); matching
--                  against runs happens in the app, in TypeScript, and the results are persisted as
-- segment_efforts  one row per (segment, run, start index): the elapsed time of that traversal. Medals
--                  are not stored: gold/silver/bronze are the user's 1st/2nd/3rd fastest effort on the
--                  segment, computed from this table (ties: earlier date wins).
-- routes           routes the user generated by target distance and start/end point (Valhalla pedestrian
--                  routing over OpenStreetMap) and chose to keep.
--
-- Scan bookkeeping: segments.scanned_through is the activity_details.fetched_at watermark of the last
-- full scan, so "runs needing a scan" = run-type details with a polyline and fetched_at > scanned_through.
-- A partial scan (opening one run) writes efforts without moving the watermark.
--
-- All three are client-synced tables under owner-only RLS. segments and routes carry updated_at and
-- the lww_guard trigger (the app sets updated_at on each update); efforts are insert/delete only, so
-- they have neither.

-- ---------------------------------------------------------------- segments

create table public.segments (
  id                 uuid primary key default gen_random_uuid(),
  user_id            uuid not null references public.profiles (id) on delete cascade,
  name               text not null,
  polyline           text not null,                            -- Google encoded polyline, precision 5
  distance_m         real not null,
  start_lat          real not null,
  start_lng          real not null,
  end_lat            real not null,
  end_lng            real not null,
  bbox               real[] not null,                          -- [min_lat, min_lng, max_lat, max_lng]
  source_activity_id text references public.activities (id) on delete set null,   -- the run it was cut from
  scanned_through    timestamptz not null default 'epoch',     -- details.fetched_at watermark of the last full scan
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

comment on table public.segments is
  'User-defined trail segments cut from a run. Matched against runs in the app; scanned_through is the activity_details.fetched_at watermark of the last full scan.';

create index segments_user_idx on public.segments (user_id);

-- ---------------------------------------------------------------- segment_efforts

create table public.segment_efforts (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references public.profiles (id) on delete cascade,
  segment_id  uuid not null references public.segments (id) on delete cascade,
  activity_id text not null references public.activities (id) on delete cascade,
  elapsed_s   real not null,
  start_idx   integer not null,                                -- polyline point index where the effort starts
  end_idx     integer not null,                                -- polyline point index where the effort ends
  started_at  timestamptz,
  created_at  timestamptz not null default now(),
  unique (segment_id, activity_id, start_idx)
);

comment on table public.segment_efforts is
  'One traversal of a segment within a run, as matched by the app. Rescanning a (segment, run) pair deletes and reinserts its rows. Medals are computed from elapsed_s, not stored.';

create index segment_efforts_user_idx     on public.segment_efforts (user_id);
create index segment_efforts_segment_idx  on public.segment_efforts (segment_id);
create index segment_efforts_activity_idx on public.segment_efforts (activity_id);

-- ---------------------------------------------------------------- routes

create table public.routes (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references public.profiles (id) on delete cascade,
  name        text not null,
  polyline    text not null,                                   -- Google encoded polyline, precision 5
  distance_m  real not null,
  elev_gain_m real,
  elev_loss_m real,
  start_lat   real not null,
  start_lng   real not null,
  bbox        real[] not null,                                 -- [min_lat, min_lng, max_lat, max_lng]
  kind        text not null check (kind in ('loop', 'point_to_point')),
  provider    text,                                            -- routing provider label, e.g. "Valhalla / OpenStreetMap"
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

comment on table public.routes is
  'Saved routes generated by target distance and start/end point over real roads and paths (pedestrian routing). Not synced to the watch.';

create index routes_user_idx on public.routes (user_id);

-- ---------------------------------------------------------------- owner-only access

do $$
declare
  t text;
begin
  foreach t in array array['segments', 'segment_efforts', 'routes'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format(
      'create policy %I on public.%I for all to authenticated '
      'using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))',
      t || '_own', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end;
$$;

-- ---------------------------------------------------------------- LWW trigger (tables with updated_at only)

create trigger segments_lww before insert or update on public.segments
  for each row execute function public.lww_guard();

create trigger routes_lww before insert or update on public.routes
  for each row execute function public.lww_guard();
