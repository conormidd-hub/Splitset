/// <reference types="node" />

// Copies two facts from data/exercise_library.json into src/lib/recovery/libraryOrder.ts, so the
// app doesn't bundle the whole library file: the exercises' order (Train next breaks ties by it,
// build phase 7) and each muscle's group. Run it whenever the library changes:
//
//   cd app && npm run gen:library-order
//
// src/lib/recovery/screens.test.ts fails if the module and the library ever differ.

import { readFileSync, writeFileSync } from 'node:fs';

const lib = JSON.parse(readFileSync(new URL('../../data/exercise_library.json', import.meta.url), 'utf8')) as {
  muscles: { id: string; group: string }[];
  exercises: { slug: string }[];
};
const out = new URL('../src/lib/recovery/libraryOrder.ts', import.meta.url);

writeFileSync(out, [
  '// Generated by app/scripts/gen-library-order.ts from data/exercise_library.json. Do not edit:',
  '// change the library, then run `npm run gen:library-order`.',
  '',
  '/** Every library exercise\'s slug, in library order. */',
  'export const LIBRARY_ORDER: readonly string[] = [',
  ...lib.exercises.map((e) => `  ${JSON.stringify(e.slug)},`),
  '];',
  '',
  '/** Each muscle\'s group, as the library names it. */',
  'export const MUSCLE_GROUPS: Readonly<Record<string, string>> = {',
  ...lib.muscles.map((m) => `  ${m.id}: ${JSON.stringify(m.group)},`),
  '};',
  '',
].join('\n'));
console.log(`wrote ${out.pathname}`);
