/// <reference types="node" />

// Copies assets/body-front.svg and assets/body-back.svg, unchanged, into
// src/lib/recovery/bodySvg.ts, so the app can draw them without a Metro transformer for .svg
// files (integration notes §8). Run it whenever the SVGs change:
//
//   cd app && npm run gen:body-figure
//
// src/lib/recovery/figure.test.ts fails if the module and the files ever differ.

import { readFileSync, writeFileSync } from 'node:fs';

const asset = (view: string) => readFileSync(new URL(`../../assets/body-${view}.svg`, import.meta.url), 'utf8');
const out = new URL('../src/lib/recovery/bodySvg.ts', import.meta.url);

writeFileSync(out, [
  '// Generated by app/scripts/gen-body-figure.ts from assets/body-front.svg and assets/body-back.svg,',
  '// byte for byte. Do not edit: change the SVGs, then run `npm run gen:body-figure`.',
  '',
  `export const BODY_SVG = {`,
  `  front: ${JSON.stringify(asset('front'))},`,
  `  back: ${JSON.stringify(asset('back'))},`,
  `} as const;`,
  '',
].join('\n'));
console.log(`wrote ${out.pathname}`);
